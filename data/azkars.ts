export const createCustomDhikr = (
  time: AzkaarTime,
  params: {
    title: string;
    arabic: string;
    transliteration: string;
    translation: string;
    virtue: string;
    defaultCount: number;
    color?: string;
    glow?: string;
  }
): Dhikr => ({
  id: `custom_${Date.now()}_${Math.random().toString(36).substr(2, 6)}`,
  time,
  order: 999,
  source: 'Personnel',
  color: params.color ?? C.gold.color,
  glow: params.glow ?? C.gold.glow,
  isCustom: true,
  title: params.title,
  arabic: params.arabic,
  transliteration: params.transliteration,
  translation: params.translation,
  virtue: params.virtue,
  defaultCount: params.defaultCount,
});